export const NOTICE_KEY = 'xiuxian_notice_v1';
export const NOTICE_VER = 1;

export function noticeAccepted(){
  try{ return localStorage.getItem(NOTICE_KEY) === String(NOTICE_VER); }
  catch(e){ return false; }
}
export function acceptNotice(){
  try{ localStorage.setItem(NOTICE_KEY, String(NOTICE_VER)); }catch(e){}
  closeModal();
}
